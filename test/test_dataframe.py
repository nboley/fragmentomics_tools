@pytest.mark.skip(
    reason="Assertion-hollow: CTCF PFM consistency needs CTCF motif BED "
    "(CTCF.matches.known.hg38.bed.gz) — unrecoverable from lost S3 bucket"
)
def test_get_pfm_consistent_with_resize():
    ctcf_rdf = (
        RegionDataFrame.from_bed(CTCF_BED_FILE, ref="hg38")
        .query("name == 'CTCF_known1' and contig == 'chr1'")
        .sample(100)
    )
    pfms = {}
    freqs = {}
    for region_size in [99, 100]:
        for motif_size in range(16, 21):
            pfms[(region_size, motif_size)] = ctcf_rdf.resize_regions(100).get_pfm(
                motif_size
            )
            freqs[(region_size, motif_size)] = pfms[
                (region_size, motif_size)
            ].freqs.sum(axis=0)
    assert (freqs[(99, 16)] == freqs[(100, 16)]).all()
    expected_freq = freqs[(100, 16)]
    for region_size in [99, 100]:
        for motif_size in range(17, 21):
            if motif_size % 2 == 1:
                total_cut_off = motif_size - 16
                left_cut_off = total_cut_off // 2
                right_cut_off = total_cut_off - left_cut_off
                assert (
                    freqs[(region_size, motif_size)][left_cut_off:-right_cut_off]
                    == expected_freq
                ).all()
            else:
                cut_off = (motif_size - 16) // 2
                assert (
                    freqs[(region_size, motif_size)][cut_off:-cut_off]
                    == expected_freq
                ).all()


