def get_find_motifs_url(tf_name):
    return "http://jaspar.genereg.net/api/v1/matrix/?name={}&tax_id=9606".format(tf_name)


def _iter_cached_pfms(tf_name):
    if tf_name not in cached_pfms:
        raise KeyError("pfm for {} is not present in cached_pfms".format(tf_name))
    for matrix_id, pfm in cached_pfms[tf_name]:
        yield matrix_id, pfm


def iter_pfms(tf_name):
    find_motifs_url = get_find_motifs_url(tf_name)
    response = requests.get(find_motifs_url)
    # if we can't download the pfm, then load from the cache
    if response.status_code == 404:
        warnings.warn("404 Error; using cached pfms")
        for x in _iter_cached_pfms(tf_name):
            yield x
        return

    assert response.status_code == 200, response.status_code
    res = requests.get(find_motifs_url).json()
    assert res["next"] is None and res["previous"] is None, "Make sure that there is only one page of data"
    results = res["results"]
    if len(results) == 0 and False:
        warnings.warn(f"Could not find '{tf_name}' in JASPAR; using cached pfms")
        try:
            for x in _iter_cached_pfms(tf_name):
                yield x
        # if there is no cache pfm, then return an empty result
        except KeyError:
            return
        return

    for matrix in results:
        matrix_url = matrix["url"]
        response = requests.get(matrix_url)
        assert response.status_code == 200, response.status_code
        res = response.json()
        # This is no longer any value specified in res['species']
        # assert "Homo sapiens" in [x["name"] for x in res["species"]], res["species"]
        pfm = np.array([res["pfm"][base] for base in "ACGT"]).T
        yield res["matrix_id"], pfm


def get_best_pfm(tf_name):
    all_pfms = [(pfm.sum(), motif_id, pfm) for motif_id, pfm in iter_pfms(tf_name)]
    all_pfms.sort(reverse=True)
    if len(all_pfms) == 0:
        raise MissingPFMError(f"Could not find a PFM for '{tf_name}'. \nHINT: {get_find_motifs_url(tf_name)}")
    return all_pfms[0][1:]


def _process_nuc_row(row, implied_base=False):
    if implied_base:
        return None, np.array([int(x) for x in row.strip().split()])
    parts = row.split("[")
    character = parts[0].strip()
    assert character in {"A", "C", "G", "T"}, character
    weights = list(map(int, [x for x in parts[1].split(" ") if x][:-1]))
    return character, np.array(weights)


def pfm_to_logo(pfm):
    pfm_psseudo = pfm + 1
    emperical_probs = (
        pfm_psseudo / pfm_psseudo.sum(axis=1)[:, None]
    )  # probability per position of each of 4 bases.
    ic = np.log2(4) - (-(emperical_probs * np.log2(emperical_probs)).sum(axis=1)[:, None])
    motif_logo = ic * emperical_probs
    return motif_logo


def get_redundant_core_pfms(calculate_logo: bool = False, path: str = None):
    if path is None:
        path = DEFAULT_JASPAR_CORE_PATH
    try:
        with open(path) as handle:
            rows = [r.rstrip("\n") for r in handle]
    except FileNotFoundError as exc:
        raise FileNotFoundError(
            f"The JASPAR CORE 2024 vertebrates (redundant) PFM database is required but was "
            f"not found at '{path}'. This is a host-specific absolute path and will not exist "
            f"inside a container unless that directory is mounted. There is no fallback PFM set."
        ) from exc
    pfms = []
    i = 0
    while i + 4 < len(rows):
        assert rows[i][0] == ">", rows[i]
        id_parts = rows[i].strip().split("\t")
        pfm_id = id_parts[0][1:].strip()
        pfm_name = id_parts[1].strip()
        a, weightsa = _process_nuc_row(rows[i + 1], implied_base=False)
        assert a == "A"
        c, weightsc = _process_nuc_row(rows[i + 2], implied_base=False)
        assert c == "C"
        g, weightsg = _process_nuc_row(rows[i + 3], implied_base=False)
        assert g == "G"
        t, weightst = _process_nuc_row(rows[i + 4], implied_base=False)
        assert t == "T"
        pfm_i = np.swapaxes(np.stack([weightsa, weightsc, weightsg, weightst]), 0, 1)
        res_i = {"pfm_id": pfm_id, "pfm_name": pfm_name.upper(), "pfm": pfm_i}
        if calculate_logo:
            res_i["logo"] = pfm_to_logo(pfm_i)
        pfms.append(res_i)
        i += 5
    return pfms


